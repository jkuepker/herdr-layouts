// Embeds the Antonio TTFs (OFL) from the LCARS Herdr mod as base64 data URIs in plugins/lcars/fonts.ts, so the
// plugin works offline. Run from this folder: bun gen-fonts.ts
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { join } from 'node:path'

const src = join(import.meta.dir, '..', 'lcars', 'mods', 'lcars', 'fonts')
const out = join(import.meta.dir, 'plugins', 'lcars')
const uri = (file: string) => `data:font/ttf;base64,${readFileSync(join(src, file)).toString('base64')}`

writeFileSync(
  join(out, 'fonts.ts'),
  `// Generated by gen-fonts.ts from Antonio-Regular.ttf and Antonio-Bold.ttf (SIL OFL 1.1, see OFL.txt). Do not edit.
export const antonioRegular = '${uri('Antonio-Regular.ttf')}'
export const antonioBold = '${uri('Antonio-Bold.ttf')}'
`,
)
copyFileSync(join(src, 'OFL.txt'), join(out, 'OFL.txt'))
console.log('wrote', join(out, 'fonts.ts'))
